"use client";

import { motion } from "motion/react";
import { useMemo, type ReactNode } from "react";
import {
  BellOffIcon,
  BorrowIcon,
  CheckIcon,
  ChevronRightIcon,
  InfoIcon,
  RequestIcon,
  SendIcon,
  ShieldIcon,
} from "@/components/pocket/icons";
import { dayLabel, rowStamp } from "@/components/pocket/ledger/TransactionRow";
import { SCREEN, stagger } from "@/components/pocket/theme";
import { Button } from "@/components/pocket/ui/Button";
import { ScreenHeader } from "@/components/pocket/ui/ScreenHeader";
import { EmptyState, ListSkeleton } from "@/components/pocket/ui/States";
import { useMounted } from "@/components/pocket/ui/useMounted";
import { cn } from "@/lib/utils";
import type {
  NotificationKind,
  PocketNotification,
} from "@/features/notifications/notification.types";

/**
 * Notifications.
 *
 * Everything here is generated by this build, and the list says so at the
 * bottom rather than dressing itself up as a feed. Two entries point at real
 * ledger ids, so tapping one opens the actual receipt instead of a paraphrase
 * of it — the notification is a way into the record, never a second copy that
 * can disagree with it.
 *
 * Marking read happens on press for every row, including the ones with
 * nowhere to go. A security notice that could only be marked read by a
 * separate button would sit there looking unhandled for no reason; press
 * anywhere means "seen", and the chevron is what distinguishes "seen and here
 * is the receipt" from "seen".
 */
export function NotificationsScreen({
  notifications,
  onBack,
  onOpenTransaction,
  onOpenRequest,
  onMarkRead,
  onMarkAllRead,
  onClearAll,
}: {
  notifications: PocketNotification[];
  onBack: () => void;
  onOpenTransaction: (transactionId: string) => void;
  onOpenRequest: (requestId: string) => void;
  onMarkRead: (id: string) => void;
  onMarkAllRead: () => void;
  onClearAll: () => void;
}) {
  const mounted = useMounted();
  const unread = notifications.filter((note) => !note.read).length;

  /**
   * Same day-grouping as the ledger, and deliberately the same function: a
   * notification that arrived with a payment should sit under the same heading
   * that payment does.
   */
  const groups = useMemo(() => {
    const out: { label: string; items: PocketNotification[] }[] = [];
    for (const note of notifications) {
      const label = dayLabel(note.createdAt);
      const last = out[out.length - 1];
      if (last && last.label === label) last.items.push(note);
      else out.push({ label, items: [note] });
    }
    return out;
  }, [notifications]);

  function open(note: PocketNotification) {
    onMarkRead(note.id);
    // A request notice lands on the request, where it can actually be answered.
    // Sending it to a payment would be pointing at money that has not moved.
    if (note.requestId) onOpenRequest(note.requestId);
    else if (note.transactionId) onOpenTransaction(note.transactionId);
  }

  return (
    <div className={SCREEN}>
      <ScreenHeader
        title="Notifications"
        onBack={onBack}
        action={
          /*
           * One slot, holding whichever action is the useful one next.
           *
           * With unread notices waiting, "Mark all" is the action; once there
           * are none, the same slot becomes "Clear all". Offering both at once
           * would put an empty-the-list button next to unseen notices, and the
           * gate is the reason clearing needs no confirmation — the control
           * simply is not there while something is unread.
           */
          unread > 0 ? (
            <Button size="sm" variant="ghost" onClick={onMarkAllRead}>
              Mark all
            </Button>
          ) : notifications.length > 0 ? (
            <Button size="sm" variant="ghost" onClick={onClearAll}>
              Clear all
            </Button>
          ) : null
        }
      />

      {!mounted ? (
        <ListSkeleton rows={4} />
      ) : notifications.length === 0 ? (
        <EmptyState
          icon={<BellOffIcon size={22} />}
          title="Nothing new"
          description="Payments, requests and account notices will appear here."
        />
      ) : (
        <div className="space-y-5">
          {groups.map((group, groupIndex) => (
            <section key={group.label} className="space-y-1">
              <motion.h2
                initial={{ opacity: 0 }}
                animate={{ opacity: 1 }}
                transition={stagger(groupIndex, 0.04)}
                className="pk-m px-1 pb-1 font-semibold uppercase"
              >
                {group.label}
              </motion.h2>

              <div className="pk-card !px-3 !py-1">
                {group.items.map((note, index) => (
                  <motion.div
                    key={note.id}
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={stagger(index, 0.04)}
                  >
                    <NotificationRow note={note} onPress={() => open(note)} />
                  </motion.div>
                ))}
              </div>
            </section>
          ))}
        </div>
      )}

      <p className="pk-m mt-5 px-1 leading-relaxed">
        Every notification here was written by this demo. No push service is
        connected, and none of these describe activity on a blockchain.
      </p>
    </div>
  );
}

/**
 * How each kind of notice presents itself.
 *
 * The tint is decided by what the notice *means*, not what kind it is: money
 * arriving is green whether it arrived as a payment or as someone settling a
 * request, and a notice that is only information gets no colour at all. Green
 * is reserved for the two kinds that report money in, so that the colour keeps
 * meaning something when the list is skimmed.
 */
const PRESENTATION: Record<
  NotificationKind,
  { icon: ReactNode; tone: string }
> = {
  payment_received: {
    icon: <RequestIcon size={16} />,
    tone: "!bg-[color-mix(in_srgb,var(--g)_14%,transparent)] text-[var(--g-ink)]",
  },
  payment_sent: {
    icon: <SendIcon size={16} />,
    tone: "bg-[var(--s2)] text-[var(--m)]",
  },
  request_received: {
    icon: <BorrowIcon size={16} />,
    // The exclamation mark is load-bearing: `.pk-ico` is unlayered CSS that
    // sets its own background, and an unlayered rule beats a layered utility
    // no matter how specific the utility is. Without it every disc in this
    // list silently falls back to grey.
    tone: "!bg-[color-mix(in_srgb,var(--p)_16%,transparent)] text-[var(--p)]",
  },
  request_paid: {
    icon: <CheckIcon size={16} />,
    tone: "!bg-[color-mix(in_srgb,var(--g)_14%,transparent)] text-[var(--g-ink)]",
  },
  security: {
    icon: <ShieldIcon size={16} />,
    // Yellow cannot carry ink on its own — a legible warning has to be the
    // yellow mixed back toward the text colour, the same way the rest of the
    // app draws a caution.
    tone: "!bg-[color-mix(in_srgb,var(--y)_22%,transparent)] text-[color-mix(in_srgb,var(--y)_42%,var(--t))]",
  },
  product: {
    icon: <InfoIcon size={16} />,
    tone: "bg-[var(--s2)] text-[var(--m)]",
  },
};

function NotificationRow({
  note,
  onPress,
}: {
  note: PocketNotification;
  onPress: () => void;
}) {
  const mounted = useMounted();
  const { icon, tone } = PRESENTATION[note.kind];
  const stamp = mounted ? rowStamp(note.createdAt) : "";

  return (
    <motion.button
      type="button"
      whileTap={{ scale: 0.99 }}
      onClick={onPress}
      className={cn(
        "pk-li w-full text-left outline-none",
        // Unread is carried by the surface rather than by a tint: a whole row
        // sitting on the inset colour is visible at a glance down the list,
        // where six differently-coloured dots would not be.
        !note.read && "bg-[var(--s2)]",
      )}
    >
      <span className={cn("pk-ico", tone)}>{icon}</span>

      <span className="pk-f">
        <b className="truncate text-[14px]">{note.title}</b>

        <span className="pk-m mt-0.5 block leading-relaxed">{note.body}</span>

        {stamp ? <span className="pk-m mt-1 block">{stamp}</span> : null}
      </span>

      {/* Only where a tap actually goes somewhere. A chevron on a notice that
          stays put would promise a screen that does not exist. */}
      {note.requestId || note.transactionId ? (
        <ChevronRightIcon
          size={16}
          className="mt-1 shrink-0 text-[var(--m)]"
          aria-hidden="true"
        />
      ) : null}
    </motion.button>
  );
}
